def row(
    rid: int,
    status: str,
    pending: bool,
    abnormal: bool,
    collected_at: str,
    biz_date: str,
    fields: dict[str, Any],
    *,
    confirmed: bool = False,
    returned: bool = False,
) -> dict[str, Any]:
    """组装一条带收口元数据的记录，字段顺序保持与既有模块一致。"""
    data: dict[str, Any] = {"id": rid, "status": status, "pending": pending, "abnormal": abnormal}
    data.update(fields)
    data.update({
        "collected_at": collected_at,
        "biz_date": biz_date,
        "confirmed": confirmed,
        "returned": returned,
    })
    return data


